def demo_etm_ordering():
    hdr("DEMO 8 — Encrypt-then-MAC vs MAC-then-Encrypt Comparison")

    print(f"""
  {GRAY}The order of encryption and MAC computation critically affects
  security. Three schemes exist:{RESET}

  {GREEN}Encrypt-then-MAC (EtM) — THIS PROJECT:{RESET}
    MAC = HMAC(IV || ciphertext, K_m)
    Receiver: verify MAC → then decrypt
    ✔ No decryption oracle exposed to attacker
    ✔ Immune to padding oracle attacks (POODLE, Lucky13, BEAST)
    ✔ Used in: TLS 1.3, IPSec ESP, SSH (recommended extensions)

  {RED}MAC-then-Encrypt (MtE) — DEPRECATED:{RESET}
    MAC = HMAC(plaintext, K_m)
    Ciphertext = AES(plaintext || MAC, K_s)
    Receiver must decrypt BEFORE verifying MAC
    ✘ Exposes padding oracle — POODLE attack (2014) exploited this
    ✘ Used in TLS 1.2 (now deprecated), SSL 3.0 (broken)

  {RED}Encrypt-and-MAC (E&M) — SSH default:{RESET}
    MAC = HMAC(plaintext, K_m)   ← MAC over PLAINTEXT
    Ciphertext = AES(plaintext, K_s)
    ✘ MAC leaks plaintext information (deterministic function of plaintext)
    """)

    K_s = generate_aes_key(32)
    K_m = generate_mac_key(32)
    engine = AESEngine(K_s, K_m)

    payload = b'{"command": "BRAKE", "force": 0.8}'
    packet  = engine.encrypt(payload, "VH-007", 1)

    sub("Our EtM implementation — verifying order")
    dat("HMAC scope includes:", "IV + ciphertext + vehicle_id + seq + timestamp")
    dat("HMAC covers plaintext?","No — HMAC is over CIPHERTEXT (EtM)")
    dat("Decrypt attempted if HMAC fails?", "No — ValueError raised immediately")
    ok("Encrypt-then-MAC correctly implemented — padding oracle impossible")

    # Demonstrate: if we tamper, decrypt is NEVER called
    sub("Confirming decryption is skipped on HMAC failure")
    bad = copy.deepcopy(packet)
    bad.ciphertext = b'\x00' * len(bad.ciphertext)
    try:
        engine.decrypt(bad)
        fail("UNEXPECTED: decryption succeeded on tampered packet")
    except ValueError as e:
        ok(f"decrypt() raised ValueError at HMAC check — AES never ran")
        info(f"Error: {str(e)[:70]}")


