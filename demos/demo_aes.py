def demo_padding():
    hdr("DEMO 7 — PKCS7 Padding Internals")

    print(f"""
  {GRAY}AES block size = 16 bytes. All inputs must be padded to a multiple
  of 16 bytes. PKCS7: append N bytes each of value N, where N is the
  number of bytes needed. If already aligned, append 16 bytes of 0x10.{RESET}
    """)

    test_cases = [
        b"speed=87.4",                          # 10 bytes  → pad 6
        b"VH-001|TELEMETRY|B2",                # 20 bytes  → pad 12
        b"A" * 16,                              # 16 bytes  → pad 16 (full block)
        b"B" * 31,                              # 31 bytes  → pad 1
        b"C" * 32,                              # 32 bytes  → pad 16
    ]

    sub("Padding examples")
    print()
    for msg in test_cases:
        padded = _pkcs7_pad(msg)
        n      = padded[-1]            # last byte IS the pad value
        unp    = _pkcs7_unpad(padded)
        ok_str = "✔" if unp == msg else "✘"

        print(f"  {GRAY}Input:  {RESET}{WHITE}{repr(msg[:24])}{'...' if len(msg)>24 else ''}{RESET}")
        print(f"  {GRAY}Length: {len(msg)} → padded: {len(padded)} bytes "
              f"(pad value N={n}, 0x{n:02X}){RESET}")
        print(f"  {GRAY}Last 4 padded bytes: {padded[-4:].hex()}  "
              f"Round-trip {ok_str}{RESET}")
        print()

    ok("PKCS7 always produces block-aligned output")
    ok("Unpadding is unambiguous — last byte always encodes the pad length")
    ok("Padding oracle attack: prevented by Encrypt-then-MAC (HMAC checked before unpad)")


