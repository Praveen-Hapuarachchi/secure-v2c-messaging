def demo_ecb_vs_cbc():
    hdr("DEMO 5 — ECB Pattern Leakage vs CBC Confidentiality (Lecture 4)")

    print(f"""
  {GRAY}Core concept (Lecture 4):{RESET}
  ECB (Electronic Codebook): each 16-byte block encrypted
  independently with the same key. Identical input blocks → identical
  output blocks. Structural patterns survive into ciphertext.

  CBC (Cipher Block Chaining): each block XORed with the previous
  ciphertext block before encryption. Identical input blocks →
  completely different output blocks. No pattern leakage.

  This demo uses structured vehicle telemetry to show how ECB leaks
  the REPETITIVE STRUCTURE of vehicle messages while CBC does not.
    """)

    K_s     = generate_aes_key(32)
    ecb_eng = ECBDemoEngine(K_s)

    # Craft messages where some 16-byte blocks are IDENTICAL
    # "TELEMETRY|VH-00" is exactly 16 bytes
    base_block   = b"TELEMETRY|VH-00X"   # 16 bytes exactly
    assert len(base_block) == 16

    # Three messages that share the same first block
    messages = [
        base_block + b"speed=087.4km/h|fuel=063%|zone=B2|temp=091.5",
        base_block + b"speed=087.4km/h|fuel=063%|zone=B2|temp=091.5",   # same
        base_block + b"speed=100.0km/h|fuel=040%|zone=A1|temp=095.2",   # different suffix
    ]

    sub("ECB mode — identical blocks produce identical ciphertext")
    ecb_results = []
    for i, msg in enumerate(messages):
        ct = ecb_eng.encrypt_ecb(msg)
        ecb_results.append(ct)
        block0_hex = ct[:16].hex()
        block1_hex = ct[16:32].hex()
        print(f"  {GRAY}Msg {i+1} Block0 (ECB):{RESET} {WHITE}{block0_hex}{RESET}")
        print(f"  {GRAY}Msg {i+1} Block1 (ECB):{RESET} {WHITE}{block1_hex}{RESET}")
        print()

    # Check if block 0 of messages 1 and 2 are identical (they share the same plaintext block)
    if ecb_results[0][:16] == ecb_results[1][:16] == ecb_results[2][:16]:
        warn("ECB: All 3 message header blocks are IDENTICAL in ciphertext!")
        warn("Attacker can detect: 'same vehicle type / same message prefix'")
        warn("Even without the key — pure ciphertext pattern analysis")
    print()

    sub("CBC mode — identical blocks produce DIFFERENT ciphertext")
    # For CBC we need a proper AES engine
    K_m    = generate_mac_key(32)
    engine = AESEngine(K_s, K_m)

    cbc_results = []
    for i, msg in enumerate(messages):
        pkt = engine.encrypt(msg, f"VH-{i:03d}", i + 1)
        cbc_results.append(pkt)
        block0_hex = pkt.ciphertext[:16].hex()
        block1_hex = pkt.ciphertext[16:32].hex() if len(pkt.ciphertext) >= 32 else "N/A"
        print(f"  {GRAY}Msg {i+1} Block0 (CBC):{RESET} {WHITE}{block0_hex}{RESET}")
        print(f"  {GRAY}Msg {i+1} Block1 (CBC):{RESET} {WHITE}{block1_hex}{RESET}")
        print(f"  {GRAY}Msg {i+1} IV    (CBC):{RESET} {CYAN}{pkt.iv.hex()}{RESET}")
        print()

    # Block 0 of messages 1 and 2 must be DIFFERENT (different IVs)
    if cbc_results[0].ciphertext[:16] != cbc_results[1].ciphertext[:16]:
        ok("CBC: All blocks are UNIQUE — even for identical input blocks")
        ok("Attacker cannot detect repeated messages or structure")
        ok("Semantic security achieved: ciphertext reveals NOTHING about plaintext")
    else:
        fail("UNEXPECTED: CBC produced identical blocks!")

    sub("Visual block comparison summary")
    print(f"  {'Message pair':<20} {'ECB Block0 same?':<22} {'CBC Block0 same?'}")
    print(f"  {'-'*60}")
    for i in range(len(messages)):
        for j in range(i+1, len(messages)):
            ecb_same = "YES ← LEAKS!" if ecb_results[i][:16] == ecb_results[j][:16] else "No"
            cbc_same = "YES" if cbc_results[i].ciphertext[:16] == cbc_results[j].ciphertext[:16] else "No ✔"
            print(f"  Msg {i+1} vs Msg {j+1}:          {ecb_same:<22} {cbc_same}")


