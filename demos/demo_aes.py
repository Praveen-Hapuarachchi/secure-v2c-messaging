def demo_normal():
    hdr("DEMO 1 — Normal AES-256-CBC Encryption & Decryption")

    print(f"""
  {GRAY}Scenario:{RESET}
  Vehicle VH-001 sends encrypted telemetry to the controller.
  The payload is encrypted with AES-256-CBC (K_s) and authenticated
  with HMAC-SHA256 (K_m) using the Encrypt-then-MAC pattern.

  {GRAY}Syllabus:{RESET} Lecture 4 — AES block cipher, CBC mode.
  Lecture 6 — HMAC integration (Encrypt-then-MAC).
    """)

    K_s = generate_aes_key(32)
    K_m = generate_mac_key(32)

    sub("Step 1 — Key generation")
    dat("K_s (AES-256, first 8B):", K_s[:8].hex() + "...  [32 bytes / 256 bits]")
    dat("K_m (HMAC, first 8B):",    K_m[:8].hex() + "...  [32 bytes / 256 bits]")
    dat("K_s == K_m?",             str(K_s == K_m) + "  (must be False — key separation)")
    ok("Keys are distinct and generated by CSPRNG")

    sub("Step 2 — Vehicle encrypts telemetry")
    encryptor = VehicleEncryptor("VH-001", K_s, K_m)
    payload   = {
        "speed_kmh"   : 87.4,
        "latitude"    : 6.0535,
        "longitude"   : 80.2210,
        "fuel_pct"    : 63.2,
        "engine_temp" : 91.5,
        "zone"        : "B2",
    }

    packet = encryptor.send(payload)

    plaintext_bytes = json.dumps(payload, sort_keys=True).encode()
    dat("Plaintext (UTF-8):",   json.dumps(payload))
    dat("Plaintext length:",    f"{len(plaintext_bytes)} bytes")
    dat("IV (16 bytes):",       packet.iv.hex())
    dat("Ciphertext length:",   f"{len(packet.ciphertext)} bytes")
    dat("Ciphertext (first 16B):", packet.ciphertext[:16].hex() + "...")
    dat("HMAC tag:",            packet.hmac_tag.hex())
    dat("Sequence no.:",        str(packet.sequence_no))

    # Confirm plaintext is NOT visible in ciphertext
    info("Checking that plaintext bytes do not appear in ciphertext...")
    if plaintext_bytes[:8] in packet.ciphertext:
        warn("Plaintext prefix found in ciphertext — this should never happen!")
    else:
        ok("Plaintext is NOT visible in ciphertext — confidentiality achieved")

    sub("Step 3 — Controller decrypts and verifies")
    decryptor = ControllerDecryptor(K_s, K_m)
    result    = decryptor.receive(packet)

    dat("Status:",   result["status"])
    dat("Reason:",   result["reason"])
    dat("Payload:",  json.dumps(result["payload"]))

    if result["status"] == "OK":
        ok("Decryption and HMAC verification both passed")
        ok("Payload recovered identically to the original")
        assert result["payload"] == payload, "Payload mismatch!"
    else:
        fail(f"Unexpected: {result['reason']}")


