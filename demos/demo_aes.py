def demo_iv_swap():
    hdr("DEMO 4 — IV-Swap Attack Prevention")

    print(f"""
  {GRAY}Scenario:{RESET}
  In CBC mode, flipping a bit in the IV predictably flips the
  corresponding bit in the FIRST decrypted plaintext block.
  If the IV were NOT authenticated (not in HMAC scope), an attacker
  could manipulate the IV to corrupt targeted fields in block 1.

  Our design includes the IV in the HMAC scope:
    HMAC( IV || ciphertext || vehicle_id || seq || timestamp, K_m )
  So any IV modification invalidates the HMAC tag.

  {GRAY}Syllabus:{RESET} Lecture 4 — CBC decryption formula:
    P[0] = D(C[0], K) ⊕ IV
  Flipping bit j of IV flips bit j of P[0] — controllable by attacker
  WITHOUT modifying C[0]. The HMAC over IV prevents this.
    """)

    K_s = generate_aes_key(32)
    K_m = generate_mac_key(32)
    enc = VehicleEncryptor("VH-004", K_s, K_m)
    dec = ControllerDecryptor(K_s, K_m)

    sub("Step 1 — Original packet")
    packet = enc.send({"action": "SET_SPEED", "value": 60})
    ok(f"IV: {packet.iv.hex()}")

    sub("Step 2 — Trudy flips bit 7 of the IV (targeting block 1 of plaintext)")
    tampered    = copy.deepcopy(packet)
    iv_list     = bytearray(tampered.iv)
    iv_list[0] ^= 0x80           # flip MSB of byte 0
    tampered.iv = bytes(iv_list)
    info(f"Original IV[0]: 0x{packet.iv[0]:02X}  →  Tampered IV[0]: 0x{tampered.iv[0]:02X}")

    sub("Step 3 — Controller rejects — IV modification invalidates HMAC")
    result = dec.receive(tampered)
    dat("Status:", result["status"])
    if result["status"] == "HMAC_FAIL":
        ok("IV-swap attack detected — IV is included in HMAC scope")
        ok("Attacker cannot selectively corrupt plaintext block 1")
    else:
        fail("UNEXPECTED: IV swap was accepted!")


