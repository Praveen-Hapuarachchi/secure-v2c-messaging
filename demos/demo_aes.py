def demo_randomness():
    hdr("DEMO 2 — Ciphertext Randomness via Fresh IV per Message")

    print(f"""
  {GRAY}Scenario:{RESET}
  VH-002 sends the IDENTICAL payload four times. In ECB mode,
  all four would produce identical ciphertext. In CBC with a fresh
  random IV, each encryption produces a unique ciphertext even
  though the plaintext and key are constant.

  {GRAY}Syllabus:{RESET} Lecture 4 — "IV is required to ensure that identical
  plaintexts encrypt to different ciphertexts."
  This is semantic security — the attacker learns nothing about
  message frequency or content from ciphertext patterns.
    """)

    K_s = generate_aes_key(32)
    K_m = generate_mac_key(32)
    enc = VehicleEncryptor("VH-002", K_s, K_m)

    payload = {"status": "IDLE", "speed_kmh": 0.0}
    print()

    ciphertexts = []
    ivs         = []
    for i in range(4):
        pkt = enc.send(payload)
        ciphertexts.append(pkt.ciphertext)
        ivs.append(pkt.iv)
        dat(f"  Message {i+1} IV:",         pkt.iv.hex())
        dat(f"  Message {i+1} CT (first 16B):", pkt.ciphertext[:16].hex())
        print()

    # Verify all ciphertexts are distinct
    unique_cts = len(set(ciphertexts))
    unique_ivs = len(set(ivs))

    if unique_cts == 4 and unique_ivs == 4:
        ok(f"All 4 ciphertexts are unique (despite identical plaintext)")
        ok(f"All 4 IVs are unique (CSPRNG ensures unpredictability)")
        ok("Attacker cannot detect repeated transmissions — semantic security")
    else:
        fail(f"Collision detected! unique_cts={unique_cts} unique_ivs={unique_ivs}")


