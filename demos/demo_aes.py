    dat("  of which metadata:",   f"{len(wire_bytes) - len(packet.iv) - len(packet.ciphertext) - len(packet.hmac_tag)} bytes")

    sub("Round-trip field verification")
    fields = ["iv", "ciphertext", "hmac_tag", "vehicle_id", "sequence_no"]
    for f in fields:
        orig = getattr(packet, f)
        recv = getattr(recovered, f)
        if orig == recv:
            ok(f"{f}: preserved exactly")
        else:
            fail(f"{f}: MISMATCH!")

    sub("Decryption of deserialised packet")
    result = dec.receive(recovered)
    dat("Status:", result["status"])
    if result["status"] == "OK":
        ok("Full pipeline: encrypt → serialise → deserialise → decrypt: SUCCESS")
    else:
        fail(f"Pipeline failed: {result['reason']}")


