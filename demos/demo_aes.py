def demo_tampering():
    hdr("DEMO 3 — Tampered Ciphertext Detection (HMAC Guards Decryption)")

    print(f"""
  {GRAY}Scenario:{RESET}
  Trudy intercepts the encrypted packet and flips a bit in the
  ciphertext, attempting to inject modified data. The HMAC check
  (computed over the ciphertext in Encrypt-then-MAC) catches this
  BEFORE any decryption is attempted.

  {GRAY}Syllabus:{RESET} Lecture 6 — HMAC provides integrity.
  Lecture 4 — CBC error propagation: "a bit error in ciphertext
  block i corrupts the decryption of blocks i and i+1".
  Our design catches the tampering at the HMAC layer, not via
  the CBC error propagation (which would still produce some
  decryptable blocks — a weaker detection method).
    """)

    K_s = generate_aes_key(32)
    K_m = generate_mac_key(32)
    enc = VehicleEncryptor("VH-003", K_s, K_m)
    dec = ControllerDecryptor(K_s, K_m)

    sub("Step 1 — Original packet encrypted successfully")
    packet  = enc.send({"command": "OPEN_GATE", "zone": "C3"})
    result1 = dec.receive(packet)
    dat("Original status:", result1["status"])
    ok("Original packet accepted")

    sub("Step 2 — Trudy flips a byte in the ciphertext")
    tampered         = copy.deepcopy(packet)
    ct_list          = bytearray(tampered.ciphertext)
    target_byte      = len(ct_list) // 2        # middle of ciphertext
    original_byte    = ct_list[target_byte]
    ct_list[target_byte] ^= 0xFF               # flip all 8 bits
    tampered.ciphertext  = bytes(ct_list)

    info(f"Byte at position {target_byte}: 0x{original_byte:02X} → 0x{ct_list[target_byte]:02X}")
    info("Trudy cannot recompute HMAC without K_m — sends stale tag")

    sub("Step 3 — Controller rejects tampered packet at HMAC layer")
    # Use a fresh decryptor so the replay counter doesn't interfere —
    # we want to demonstrate HMAC_FAIL specifically, not REPLAY.
    dec2    = ControllerDecryptor(K_s, K_m)
    result2 = dec2.receive(tampered)
    dat("Tampered packet status:", result2["status"])
    dat("Reason:", result2["reason"][:80] + "...")

    if result2["status"] == "HMAC_FAIL":
        ok("Ciphertext tampering detected by HMAC BEFORE any decryption")
        ok("Padding oracle attack surface: ZERO (decrypt never called)")
        ok("Trudy's modified GATE command was NOT executed")
    else:
        fail("UNEXPECTED: tampered packet was accepted!")


