def demo_multi_vehicle():
    hdr("DEMO 10 — Multi-Vehicle Encrypted Session")

    print(f"""
  {GRAY}Scenario:{RESET}
  Three vehicles each have unique AES and MAC key pairs.
  The controller handles all three simultaneously, maintaining
  separate replay counters per vehicle.
    """)

    vehicles = {
        "VH-010": (generate_aes_key(32), generate_mac_key(32)),
        "VH-011": (generate_aes_key(32), generate_mac_key(32)),
        "VH-012": (generate_aes_key(32), generate_mac_key(32)),
    }

    encryptors = {
        vid: VehicleEncryptor(vid, ks, km)
        for vid, (ks, km) in vehicles.items()
    }
    decryptors = {
        vid: ControllerDecryptor(ks, km)
        for vid, (ks, km) in vehicles.items()
    }

    messages = [
        ("VH-010", {"speed": 55.0, "zone": "A1"}),
        ("VH-011", {"speed": 72.3, "zone": "B2"}),
        ("VH-010", {"alert": "BRAKE_WARN"}),
        ("VH-012", {"speed": 90.0, "zone": "C3"}),
        ("VH-011", {"speed": 68.1, "fuel": 42.0}),
        ("VH-012", {"status": "IDLE"}),
    ]

    print()
    for vid, payload in messages:
        pkt    = encryptors[vid].send(payload)
        result = decryptors[vid].receive(pkt)
        status_str = f"{GREEN}OK{RESET}" if result["status"] == "OK" else f"{RED}{result['status']}{RESET}"
        print(f"  {GRAY}{vid}{RESET}  seq={pkt.sequence_no}  "
              f"ct={len(pkt.ciphertext)}B  "
              f"status={status_str}  "
              f"payload={json.dumps(result['payload'])}")

    sub("Cross-vehicle key isolation test")
    # VH-010's packet should be rejected by VH-011's decryptor
    pkt_010 = encryptors["VH-010"].send({"test": True})
    result_cross = decryptors["VH-011"].receive(pkt_010)
    if result_cross["status"] == "HMAC_FAIL":
        ok("Cross-vehicle key isolation confirmed — VH-010 packet rejected by VH-011 decryptor")
    else:
        fail("UNEXPECTED: cross-vehicle packet accepted!")


