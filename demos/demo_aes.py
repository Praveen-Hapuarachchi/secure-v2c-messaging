def demo_iv_reuse():
    hdr("DEMO 6 — IV Reuse Vulnerability (Plaintext XOR Leakage)")

    print(f"""
  {GRAY}Scenario:{RESET}
  A BROKEN implementation reuses the same IV for two messages.
  If an attacker knows one plaintext (a common assumption — known-
  plaintext attack), they can XOR the two ciphertexts to recover
  the other plaintext. This is identical to the OTP two-time pad
  vulnerability discussed in Lecture 3.

  Formula:
    C1[0] = E(P1[0] ⊕ IV, K)
    C2[0] = E(P2[0] ⊕ IV, K)
    C1[0] ⊕ C2[0] = E(P1[0] ⊕ IV, K) ⊕ E(P2[0] ⊕ IV, K)

  When IV is reused, the inner ⊕ IV terms cancel:
    The E() function creates a one-time pad stream from (P[i-1], K)
    → XOR of two ciphertexts = XOR of two plaintexts
    → If P1[0] is KNOWN, P2[0] = C1[0] ⊕ C2[0] ⊕ P1[0]

  {GRAY}Syllabus:{RESET} Lecture 3 — "OTP depth attack: if two messages are
  encrypted with the same OTP key, XOR of ciphertexts = XOR of
  plaintexts." CBC with reused IV is IDENTICAL to this attack.
  Our design calls generate_iv() for every message — this demo
  shows what happens when this rule is broken.
    """)

    K_s = generate_aes_key(32)

    # ── Reuse the SAME IV for two messages ─────────────────────────────
    REUSED_IV   = generate_iv()   # a single IV used twice (WRONG!)
    plaintext_1 = b"speed=087 zone=B2"    # Trudy knows this (known-plaintext)
    plaintext_2 = b"speed=999 zone=A0"    # this is the SECRET message

    # Pad both
    p1_padded = _pkcs7_pad(plaintext_1)
    p2_padded = _pkcs7_pad(plaintext_2)

    # Encrypt both with SAME IV (simulating broken implementation)
    ct1 = _aes_cbc_encrypt_raw(p1_padded, K_s, REUSED_IV)
    ct2 = _aes_cbc_encrypt_raw(p2_padded, K_s, REUSED_IV)

    sub("Setup — broken system reuses IV")
    dat("Plaintext 1 (known):", plaintext_1.decode())
    dat("Plaintext 2 (secret):",plaintext_2.decode())
    dat("Reused IV:",           REUSED_IV.hex())
    dat("Ciphertext 1 (16B):",  ct1[:16].hex())
    dat("Ciphertext 2 (16B):",  ct2[:16].hex())

    sub("Attack — Trudy XORs ciphertexts and known plaintext (block 1 only)")
    # XOR of block 0 ciphertexts
    xor_cts   = bytes(a ^ b for a, b in zip(ct1[:16], ct2[:16]))
    # XOR with known plaintext 1 padded to 16 bytes
    p1_block0 = p1_padded[:16]
    recovered = bytes(a ^ b for a, b in zip(xor_cts, p1_block0))

    dat("CT1 ⊕ CT2 (block 0):", xor_cts.hex())
    dat("(CT1⊕CT2) ⊕ P1[0]:", recovered.decode(errors='replace'))

    if recovered == p2_padded[:16]:
        warn("IV REUSE ATTACK SUCCEEDED — secret block 1 recovered!")
        warn(f"Recovered: '{recovered.decode(errors='replace')}'")
        warn("This is exactly the OTP two-time pad attack from Lecture 3!")
    print()

    sub("Our implementation — fresh IV prevents this attack")
    iv1 = generate_iv()
    iv2 = generate_iv()     # DIFFERENT IV
    ct1_safe = _aes_cbc_encrypt_raw(p1_padded, K_s, iv1)
    ct2_safe = _aes_cbc_encrypt_raw(p2_padded, K_s, iv2)
    xor_safe = bytes(a ^ b for a, b in zip(ct1_safe[:16], ct2_safe[:16]))
    # XOR of ciphertexts with different IVs produces garbage, not plaintext XOR
    garbage = bytes(a ^ b for a, b in zip(xor_safe, p1_block0))
    dat("Safe CT1 ⊕ CT2 ⊕ P1[0]:", garbage.decode(errors='replace')[:30] + "...")
    ok("With distinct random IVs, XOR-based attack produces garbage")
    ok("generate_iv() called once per message prevents IV reuse entirely")


